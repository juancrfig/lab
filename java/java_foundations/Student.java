// Class creation
public class Student {
    
    // Variables must be initialized beforehand
    String name;
    int age;
    double gpa;
    boolean isEnrolled;

    // Class constructor declaration
    Student(String name, int age, double gpa) {
        this.name = name;
        this.age = age;
        this.gpa = gpa;
        this.isEnrolled = true;
    }
}

